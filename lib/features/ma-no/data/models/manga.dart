@freezed
abstract class Manga with _$Manga {
  const factory Manga({
    @Default("") @JsonKey(name: "manga_id") String id,
    @Default("") String title,
    @Default("") String slug,
    @Default("") @JsonKey(name: "image_url") String thumbnail,
    @Default("") @JsonKey(name: "second_title") String secondTitle,
    @Default("") String description,
    @Default("") @JsonKey(name: "age_restriction") String ageRestriction,
    @Default("") @JsonKey(name: "real_link") String realLink,
    @Default("") @JsonKey(name: "created_at") String createdAt,
    @Default("") @JsonKey(name: "updated_at") String updatedAt,
    @Default("") @JsonKey(name: "showing_date") String showingDate,
    @Default(MediaType.manga) MediaType type,
    @Default(MangaStatus.stopped) @JsonKey(name: "release_status") MangaStatus releaseStatus,
    @Default(MangaStatus.stopped) @JsonKey(name: "translation_status") MangaStatus translationStatus,
    @Default(0) @JsonKey(name: "likes_count") int likesCount,
    @Default(0) @JsonKey(name: "views_count") int viewsCount,
    @Default(0) @JsonKey(name: "average_rating") int averageRating,
    @Default(0) @JsonKey(name: "release_year") int releaseYear,
    @Default(0) @JsonKey(name: "chapters_count") int chaptersCount,
    @Default(0) @JsonKey(name: "bookmarked_count") int bookmarkedCount,
    @Default(false) @JsonKey(name: "is_bookmarked") bool isBookmarked,
    @Default(false) @JsonKey(name: "is_showed") bool isShowed,
    @Default([]) List<ManoTranslator> translators,
    @Default([]) List<ManoGenre> genres,
    @Default([]) List<ManoCategory> categories,
    @Default([]) List<Chapter> chapters,
  }) = _Manga;
  factory Manga.fromJson(Map<String, dynamic> json) => _$MangaFromJson(json);
}

